// Sort keys by length descending to match specific long phrases before generic single words
const SORTED_KEYS = Object.keys(GUJARATI_INGREDIENT_MAP).sort((a, b) => b.length - a.length);

/**
 * Returns Gujarati translation if available, otherwise returns formatted English name
 */
export function getGujaratiName(englishName: string): string {
  if (!englishName) return '';
  const trimmed = englishName.trim().toUpperCase();

  // 1. Direct exact match
  if (GUJARATI_INGREDIENT_MAP[trimmed]) {
    return GUJARATI_INGREDIENT_MAP[trimmed];
  }

  // 2. Longest substring key match (e.g. ROASTED BADAM TUKDA matches before BADAM)
  for (const key of SORTED_KEYS) {
    if (trimmed.includes(key)) {
      return GUJARATI_INGREDIENT_MAP[key];
    }
  }

  // 3. Fallback: Clean Title Case English string if no match
  return englishName
    .toLowerCase()
    .split(' ')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

/**
 * Format quantity in clean Gujarati unit display without redundant duplicates
 */
export function formatGujaratiQuantity(qty: number, unit: string): string {
  const u = (unit || 'KG').toUpperCase();
  if (u === 'KG' || u === 'KILOGRAMS') {
    if (qty < 1 && qty > 0) {
      const grams = Math.round(qty * 1000 * 100) / 100;
      return `${grams} ગ્રામ (${(Math.round(qty * 1000) / 1000).toFixed(3)} કિલો)`;
    }
    return `${(Math.round(qty * 1000) / 1000).toFixed(3)} કિલો`;
  }
  if (u === 'LTR' || u === 'LITRE') {
    if (qty < 1 && qty > 0) {
      const ml = Math.round(qty * 1000 * 100) / 100;
      return `${ml} મિલી (${(Math.round(qty * 1000) / 1000).toFixed(3)} લિટર)`;
    }
    return `${(Math.round(qty * 1000) / 1000).toFixed(3)} લિટર`;
  }
  if (u === 'GM' || u === 'GRAMS') {
    return `${qty} ગ્રામ`;
  }
  if (u === 'PCS' || u === 'PIECES') {
    return `${qty} નંગ`;
  }
  return `${qty} ${unit}`;
}
